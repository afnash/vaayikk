test("mobile swipes, center taps, page boundaries, zoom panning and completion", async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  const page = await context.newPage();
  await page.goto("/");
  await expect(page.locator(".book-card")).toHaveCount(6);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await expect(page.locator(".book-card").last()).toHaveCSS("opacity", "1");
  await page.screenshot({ path: "test-results/folio-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Start reading", exact: true }).click();
  await expect(page.locator(".reader canvas")).toBeVisible();
  await expect(page.getByRole("button", { name: "Previous page", exact: true })).toBeDisabled();
  const stage = await page.locator(".reader-stage").boundingBox();
  if (!stage) throw new Error("Missing reader stage");
  const y = stage.y + stage.height / 2;
  const cdp = await context.newCDPSession(page);
  const touch = async (type: "touchStart" | "touchMove" | "touchEnd", points: { x: number; y: number; id: number }[]) => cdp.send("Input.dispatchTouchEvent", { type, touchPoints: points });
  await touch("touchStart", [{ x: 315, y, id: 1 }]);
  await touch("touchMove", [{ x: 80, y, id: 1 }]);
  await touch("touchEnd", []);
  await expect(page.locator(".reader canvas")).toHaveAttribute("aria-label", /Page 2 of 7/);
  await expect(page.locator(".reader canvas")).toBeVisible();
  await page.touchscreen.tap(195, y);
  await expect(page.locator(".reader")).toHaveClass(/immersive/);
  await page.touchscreen.tap(195, y);
  await expect(page.locator(".reader")).not.toHaveClass(/immersive/);
  await touch("touchStart", [{ x: 150, y, id: 1 }, { x: 240, y, id: 2 }]);
  await touch("touchMove", [{ x: 80, y, id: 1 }, { x: 310, y, id: 2 }]);
  await touch("touchEnd", []);
  await expect(page.locator(".reader-stage")).toHaveClass(/is-zoomed/);
  await touch("touchStart", [{ x: 310, y, id: 1 }]);
  await touch("touchMove", [{ x: 85, y, id: 1 }]);
  await touch("touchEnd", []);
  await expect(page.locator(".reader canvas")).toHaveAttribute("aria-label", /Page 2 of 7/);
  await page.getByRole("button", { name: /Reset/ }).click();
  await page.getByRole("slider", { name: "Reading progress" }).fill("7");
  await expect(page.locator(".reader canvas")).toBeVisible();
  await expect(page.getByRole("button", { name: "Next page", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Back to library" }).click();
  await page.getByRole("group", { name: "Filter library" }).getByRole("button", { name: "Finished", exact: true }).click();
  await expect(page.locator(".book-card")).toHaveCount(1);
  await page.locator(".book-card .book-open").scrollIntoViewIfNeeded();
  const cover = await page.locator(".book-card .book-open").boundingBox();
  if (!cover) throw new Error("Missing book cover");
  await touch("touchStart", [{ x: cover.x + cover.width / 2, y: cover.y + cover.height / 2, id: 1 }]);
  await page.waitForTimeout(650); // Hold long enough to exercise the long-press gesture.
  await touch("touchEnd", []);
  await expect(page.getByRole("button", { name: "Open book", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Close panel" }).click();
  await context.close();
});

test("installed shell and local PDFs remain usable offline", async ({ page, context }) => {
  await expect(page.getByText("Ready for offline reading", { exact: true })).toBeVisible({ timeout: 60000 });
  await page.evaluate(() => navigator.serviceWorker.ready.then(() => true));
  await context.setOffline(true);
  await page.reload();
  await expect(page.locator(".book-card")).toHaveCount(6);
  await page.getByRole("button", { name: "Start reading", exact: true }).click();
  await expect(page.locator(".reader canvas")).toBeVisible();
  await page.getByRole("button", { name: "Next page", exact: true }).click();
  await expect(page.locator(".reader canvas")).toHaveAttribute("aria-label", /Page 2 of 7/);
  await expect(page.locator(".reader canvas")).toBeVisible();
  await page.getByRole("button", { name: "Back to library" }).click();
  await page.locator('input[type="file"]').setInputFiles(path.resolve("public/demo/morning.pdf"));
  await expect(page.locator(".book-card")).toHaveCount(7);
});

