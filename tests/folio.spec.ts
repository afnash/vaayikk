import { test, expect } from "@playwright/test";
import path from "node:path";

test.beforeEach(async ({ page }) => {
  await page.goto("/");
  await expect(page.locator(".book-card")).toHaveCount(6);
});

test("imports a real PDF, renders pages, bookmarks, and resumes after reload", async ({ page }) => {
  const errors: string[] = [];
  const outgoingRequests: { url: string; method: string }[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => outgoingRequests.push({ url: request.url(), method: request.method() }));
  await page.locator('input[type="file"]').setInputFiles(path.resolve("public/demo/noticing.pdf"));
  await expect(page.locator(".book-card")).toHaveCount(7);
  await page.locator(".book-card").first().getByRole("button", { name: "Read The Art of Noticing" }).click();
  await expect(page.locator(".reader canvas")).toBeVisible();
  await page.getByRole("button", { name: "Next page", exact: true }).click();
  await expect(page.locator(".reader canvas")).toHaveAttribute("aria-label", /Page 2 of 7/);
  await expect(page.locator(".reader canvas")).toBeVisible();
  await page.keyboard.press("ArrowRight");
  await expect(page.locator(".reader canvas")).toHaveAttribute("aria-label", /Page 3 of 7/);
  await page.keyboard.press("ArrowLeft");
  await expect(page.locator(".reader canvas")).toHaveAttribute("aria-label", /Page 2 of 7/);
  await expect(page.locator(".reader canvas")).toBeVisible();
  await page.getByRole("button", { name: "Bookmark this page" }).click();
  await expect(page.getByRole("button", { name: "Remove bookmark", exact: true })).toBeVisible();
  await page.getByRole("slider", { name: "Reading progress" }).fill("5");
  await expect(page.locator(".reader canvas")).toBeVisible();
  await page.getByRole("button", { name: "1 bookmark", exact: true }).click();
  await page.getByRole("button", { name: "Page 2", exact: true }).click();
  await expect(page.locator(".reader canvas")).toHaveAttribute("aria-label", /Page 2 of 7/);
  await expect(page.locator(".reader canvas")).toBeVisible();
  await page.getByRole("button", { name: "Back to library" }).click();
  await expect(page.locator(".book-card").first()).toContainText("29% read");
  await page.reload();
  await expect(page.locator(".book-card")).toHaveCount(7);
  await page.getByRole("button", { name: "Continue reading", exact: true }).click();
  await expect(page.locator(".reader canvas")).toHaveAttribute("aria-label", /Page 2 of 7/);
  await expect(page.getByRole("button", { name: "Remove bookmark", exact: true })).toBeVisible();
  await expect(page.locator(".reader canvas")).toBeVisible();
  await page.getByRole("button", { name: "1 bookmark", exact: true }).click();
  await page.getByRole("button", { name: "Delete bookmark on page 2" }).click();
  await expect(page.getByText("Save a page for later.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Close panel" }).click();
  await expect(page.getByRole("button", { name: "Bookmark this page" })).toBeVisible();
  expect(errors).toEqual([]);
  expect(outgoingRequests.filter(request => request.url.startsWith("http") && (!request.url.startsWith("http://localhost:3000/") || request.method !== "GET"))).toEqual([]);
});

